'use strict';
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { recover } = require('./propagation-state.cjs');
const fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'harness-recovery-'));
for (const dir of ['state', 'core', 'scripts/hooks']) fs.mkdirSync(path.join(fixture, dir), { recursive: true });
const token = 'HARNESS_PROBE_0123456789abcdef', id = 'harness-propagation-' + token;
fs.writeFileSync(path.join(fixture, 'core/machine.md'), 'baseline\n\nHarness validation token: ' + token + '\nconcurrent instruction change\n');
fs.writeFileSync(path.join(fixture, 'core/policy.json'), JSON.stringify({ hooks: [{ id }, { id: 'concurrent-user-hook' }] }));
fs.writeFileSync(path.join(fixture, 'scripts/hooks', id + '.js'), 'owned probe');
fs.writeFileSync(path.join(fixture, 'scripts/hooks/harness-propagation-probe.js'), 'pre-existing script');
fs.writeFileSync(path.join(fixture, 'state/propagation-journal.json'), JSON.stringify({ token, pid: 2147483647, scriptContent: 'owned probe' }));
assert.equal(recover(fixture), true);
assert.equal(fs.readFileSync(path.join(fixture, 'core/machine.md'), 'utf8'), 'baseline\nconcurrent instruction change\n');
assert.deepEqual(JSON.parse(fs.readFileSync(path.join(fixture, 'core/policy.json'))).hooks, [{ id: 'concurrent-user-hook' }]);
assert.equal(fs.readFileSync(path.join(fixture, 'scripts/hooks/harness-propagation-probe.js'), 'utf8'), 'pre-existing script');
assert(!fs.existsSync(path.join(fixture, 'scripts/hooks', id + '.js')));
assert(!fs.existsSync(path.join(fixture, 'state/propagation-journal.json')));
console.log('Propagation recovery passed: interrupted owner, concurrent edits, pre-existing script.');
